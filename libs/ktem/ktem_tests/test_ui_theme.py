"""Design-system and accessibility guards for the UI restyle (MODIFICATIONS §5.24).

The theme is generated by Gradio from ``assets/theme.py``; the global rules live in
``assets/css/tokens.css`` + ``assets/css/main.css``. A browser is the only way to judge
how it *looks*, but the properties that used to rot silently are all checkable from the
generated CSS: whether the design tokens still resolve, whether the text keeps a legal
WCAG contrast in both modes, whether the primary button is a measurable solid colour
instead of a gradient, whether a remote font sneaked back in, and whether the JavaScript
still depends on the DOM hooks the rest of the app relies on.

These tests deliberately do **not** use ``tmp_path``: this repository is developed in a
restricted Windows sandbox where pytest's temporary directories are not always
readable, and a UI guard must not fail for an environmental reason.
"""

from __future__ import annotations

import json
import re
from pathlib import Path

from ktem import assets as ktem_assets
from ktem.assets import load_css
from ktem.assets.theme import Kotaemon

#: The tests live in a sibling directory of the package, so the asset paths are
#: derived from the imported package rather than from ``__file__``.
ASSET_DIR = Path(ktem_assets.__file__).resolve().parent
TOKENS_CSS = ASSET_DIR / "css" / "tokens.css"
MAIN_CSS = ASSET_DIR / "css" / "main.css"
THEME_PY = ASSET_DIR / "theme.py"
MAIN_JS = ASSET_DIR / "js" / "main.js"
THEME_INIT_JS = ASSET_DIR / "js" / "theme_init.js"
CATALOG_ZH = ASSET_DIR / "i18n" / "zh.json"

HEX = re.compile(r"#[0-9a-fA-F]{3,8}\b")
DECLARATION = re.compile(r"--([a-z0-9-]+)\s*:\s*([^;]+);")
UI_VAR_USE = re.compile(r"var\(--ui-([a-z0-9-]+)\)")

#: Fonts that make the Chinese interface render consistently without a network request.
CJK_FAMILIES = ("PingFang SC", "Microsoft YaHei", "Noto Sans CJK SC", "Source Han Sans SC")

#: Labels the restyle introduces; each must exist in the bundled Chinese catalog, or a
#: Chinese UI shows English again (exactly the bug that made the login title English).
NEW_LABELS = (
    "# Welcome to {}!",
    "Sign in to continue",
    "New chat",
    "Rename conversation",
    "Delete conversation",
    "Toggle theme",
    "Collapse sidebar",
    "Expand sidebar",
    "Collapse information panel",
    "Expand information panel",
    "No evidence yet",
    "Evidence will appear here after you ask a question.",
)


# --------------------------------------------------------------------------- #
# reading the generated CSS
# --------------------------------------------------------------------------- #
def _theme_css() -> str:
    """The CSS Gradio generates for ``citeask`` (``:root`` + ``.dark`` blocks)."""
    return Kotaemon()._get_theme_css()


def _theme_block(css: str, selector: str) -> dict[str, str]:
    match = re.search(rf"(?m)^{re.escape(selector)} \{{\n(.*?)\n\}}", css, re.S)
    assert match, f"the generated theme has no '{selector}' block"
    return dict(DECLARATION.findall(match.group(1)))


def _resolve(variables: dict[str, str], name: str) -> str:
    """Follow ``var(--x)`` references until a literal value is reached."""
    for _ in range(12):
        assert name in variables, f"--{name} is not defined in the generated theme"
        raw = variables[name].strip()
        reference = re.fullmatch(r"var\(--([a-z0-9-]+)\)", raw)
        if reference is None:
            return raw
        name = reference.group(1)
    raise AssertionError(f"--{name} has a cyclic definition")


NAMED_COLOURS = {"white": "#ffffff", "black": "#000000"}


def _rgb(value: str) -> tuple[float, float, float]:
    value = NAMED_COLOURS.get(value.strip().lower(), value.strip())
    if re.fullmatch(r"#[0-9a-fA-F]{3}", value):
        value = "#" + "".join(channel * 2 for channel in value[1:])
    assert re.fullmatch(r"#[0-9a-fA-F]{6}", value), f"expected a literal colour, got {value!r}"
    return tuple(int(value[i : i + 2], 16) / 255 for i in (1, 3, 5))


def _luminance(value: str) -> float:
    def linear(channel: float) -> float:
        return channel / 12.92 if channel <= 0.03928 else ((channel + 0.055) / 1.055) ** 2.4

    red, green, blue = _rgb(value)
    return 0.2126 * linear(red) + 0.7152 * linear(green) + 0.0722 * linear(blue)


def _contrast(foreground: str, background: str) -> float:
    first, second = _luminance(foreground), _luminance(background)
    lighter, darker = max(first, second), min(first, second)
    return (lighter + 0.05) / (darker + 0.05)


def _mode_variables(dark: bool) -> dict[str, str]:
    css = _theme_css()
    variables = _theme_block(css, ":root")
    if dark:
        variables = {**variables, **_theme_block(css, ".dark")}
    return variables


# --------------------------------------------------------------------------- #
# theme tokens and contrast
# --------------------------------------------------------------------------- #
def test_the_theme_is_still_called_citeask():
    assert Kotaemon().name == "citeask"


def test_light_mode_text_is_readable():
    variables = _mode_variables(dark=False)
    background = _resolve(variables, "background-fill-primary")
    body = _resolve(variables, "body-text-color")
    subdued = _resolve(variables, "body-text-color-subdued")

    assert _contrast(body, background) >= 4.5, (body, background)
    assert _contrast(subdued, background) >= 4.5, (subdued, background)


def test_dark_mode_text_is_readable():
    variables = _mode_variables(dark=True)
    background = _resolve(variables, "background-fill-primary")
    body = _resolve(variables, "body-text-color")
    subdued = _resolve(variables, "body-text-color-subdued")

    assert _contrast(body, background) >= 4.5, (body, background)
    assert _contrast(subdued, background) >= 4.5, (subdued, background)


def test_links_and_primary_buttons_are_readable_in_both_modes():
    for dark in (False, True):
        variables = _mode_variables(dark=dark)
        background = _resolve(variables, "background-fill-primary")
        link = _resolve(variables, "link-text-color")
        button = _resolve(variables, "button-primary-background-fill")
        button_text = _resolve(variables, "button-primary-text-color")

        assert _contrast(link, background) >= 4.5, (dark, link, background)
        assert _contrast(button_text, button) >= 4.5, (dark, button_text, button)


def test_the_primary_button_is_a_solid_colour():
    """A gradient cannot be measured for contrast and dates the interface."""
    for dark in (False, True):
        variables = _mode_variables(dark=dark)
        assert "gradient" not in _resolve(variables, "button-primary-background-fill").lower()


def test_no_remote_font_is_requested():
    assert "GoogleFont" not in THEME_PY.read_text(encoding="utf-8")
    assert "fonts.googleapis" not in _theme_css()


def test_the_font_stack_covers_chinese():
    font = _resolve(_mode_variables(dark=False), "font")
    assert sum(family in font for family in CJK_FAMILIES) >= 2, font


