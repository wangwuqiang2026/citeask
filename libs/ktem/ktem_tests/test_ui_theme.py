def test_tokens_are_defined_once_and_come_first():
    tokens = TOKENS_CSS.read_text(encoding="utf-8")
    main = MAIN_CSS.read_text(encoding="utf-8")
    bundle = load_css()

    assert ":root" in tokens and "html.dark" in tokens
    assert bundle.index("--ui-bg:") < bundle.index(".gradio-container"), (
        "tokens.css must be concatenated before main.css"
    )
    # the dark palette lives on html.dark so it outranks Gradio's own ".dark" block
    assert "html.dark" in tokens, tokens[:200]


def test_components_use_tokens_not_raw_colours():
    assert not HEX.search(MAIN_CSS.read_text(encoding="utf-8")), (
        "main.css must not hard-code colours; put them in tokens.css"
    )


def test_every_referenced_token_is_defined():
    defined = {
        name[len("ui-") :]
        for name, _ in DECLARATION.findall(TOKENS_CSS.read_text(encoding="utf-8"))
        if name.startswith("ui-")
    }
    used = set(UI_VAR_USE.findall(MAIN_CSS.read_text(encoding="utf-8")))
    assert used <= defined, f"undefined tokens: {sorted(used - defined)}"


def test_the_bundle_carries_the_required_rules():
    bundle = load_css()
    for snippet in (
        ":focus-visible",
        "prefers-reduced-motion",
        "#chat-workspace",
        "#app-header",
        ".empty-state-title",
        ".chip-value",
    ):
        assert snippet in bundle, f"missing rule: {snippet}"
    for width in ("1024", "820"):
        pattern = rf"@media\s*\(max-width:\s*{width}px\)"
        assert re.search(pattern, bundle), f"missing breakpoint: {width}px"


