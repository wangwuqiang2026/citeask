export const dictionaries: Record<Lang, Record<MessageKey, string>> = { zh, en };

export function translate(
  lang: Lang,
  key: MessageKey,
  vars?: Record<string, string | number>,
): string {
  let text: string = dictionaries[lang][key] ?? zh[key] ?? key;
  if (vars) {
    for (const [name, value] of Object.entries(vars)) {
      // `replaceAll` is ES2021; the app targets ES2020 for the committed build.
      text = text.split(`{${name}}`).join(String(value));
    }
  }
  return text;
}

export function useT(): (key: MessageKey, vars?: Record<string, string | number>) => string {
  const lang = useUiStore((state) => state.lang) ?? "zh";
  return (key, vars) => translate(lang, key, vars);
}

export function useLang(): Lang {
  return useUiStore((state) => state.lang) ?? "zh";
}
