def test_the_information_panel_dom_hook_still_exists():
    script = MAIN_JS.read_text(encoding="utf-8")
    for snippet in (
        "#html-info-panel > div:last-child > div > details.evidence div.evidence-content",
        "toggleChatColumn",
        "scrollToCitation",
        "decorateClampedCells",
    ):
        assert snippet in script, f"main.js lost {snippet!r}"


def test_the_theme_is_persisted():
    script = THEME_INIT_JS.read_text(encoding="utf-8")
    assert "ktem-theme" in script
    assert "prefers-color-scheme" in script


def test_new_labels_are_in_the_bundled_chinese_catalog():
    catalog = json.loads(CATALOG_ZH.read_text(encoding="utf-8"))
    missing = [label for label in NEW_LABELS if label not in catalog]
    assert not missing, f"untranslated labels: {missing}"
